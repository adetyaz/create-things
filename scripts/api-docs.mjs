// Writes docs/api.md from the routes themselves: every endpoint, its method, and the comment
// above its handler (what it takes and returns). Run after adding or changing a route:
//   node.exe scripts/api-docs.mjs
// Cost: none (reads files only).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(
	path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')),
	'..'
);
const routesDir = path.join(root, 'src', 'routes');
const walk = (d) =>
	fs
		.readdirSync(d, { withFileTypes: true })
		.flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

/** The comment block right above `export const GET` (or the file's first comment). */
function docFor(source, method) {
	const at = source.search(new RegExp(`export\\s+(const|async function|function)\\s+${method}\\b`));
	if (at < 0) return '';
	const before = source.slice(0, at).trimEnd();
	if (!before.endsWith('*/')) return '';
	const start = before.lastIndexOf('/**');
	if (start < 0) return '';
	return before
		.slice(start + 3, -2)
		.split('\n')
		.map((l) => l.replace(/^\s*\*\s?/, '').trim())
		.join(' ')
		.replace(/\s+/g, ' ')
		.trim();
}

const endpoints = walk(routesDir)
	.filter((f) => f.endsWith('+server.ts'))
	.flatMap((f) => {
		const source = fs.readFileSync(f, 'utf8');
		const route = path.relative(routesDir, path.dirname(f)).split(path.sep).join('/');
		return ['GET', 'POST', 'PUT', 'PATCH', 'DELETE']
			.filter((m) =>
				new RegExp(`export\\s+(const|async function|function)\\s+${m}\\b`).test(source)
			)
			.map((method) => ({
				method,
				route: '/' + route,
				file: path.relative(root, f).split(path.sep).join('/'),
				doc: docFor(source, method)
			}));
	})
	.sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method));

const groups = new Map();
for (const e of endpoints) {
	const key = e.route.split('/')[2] ?? '';
	if (!groups.has(key)) groups.set(key, []);
	groups.get(key).push(e);
}

const esc = (s) => s.replace(/\|/g, '\\|');
let out = `# API reference

> Generated by \`node.exe scripts/api-docs.mjs\` from the comment on each route. Don't edit by hand:
> change the route's comment and run the script again.

${endpoints.length} endpoints. All take and return JSON unless noted. Who's asking comes from the
sign-in session cookie (the app), a device token (\`Authorization: Bearer ct_…\`, the extension), or
\`x-createthings-token\` (MPP callers). Errors come back as \`{ message }\` with the HTTP status.
See [architecture.md](architecture.md) for how the pieces fit and [ui-guide.md](ui-guide.md) for
which screen uses what.

`;
for (const [group, list] of groups) {
	out += `## ${group}\n\n| Method | Path | What it does |\n|---|---|---|\n`;
	for (const e of list) {
		const doc = e.doc.replace(/^(GET|POST|PUT|PATCH|DELETE)\s+\/\S+\s*:?\s*/, '');
		out += `| ${e.method} | [\`${e.route}\`](../${e.file}) | ${esc(doc) || '—'} |\n`;
	}
	out += '\n';
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'api.md'), out);
const missing = endpoints.filter((e) => !e.doc);
console.log(`docs/api.md: ${endpoints.length} endpoints, ${missing.length} without a comment`);
for (const e of missing) console.log(`  ${e.method} ${e.route}`);
